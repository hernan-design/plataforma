                    <h2 class="section-title text-center white-text">¿QUÉ ES ALDEA?</h2>
                    <p class="text-center text-about-aldea paragraph-vpadding-bottom"><b>ALDEA</b> es el programa de iNNpulsa Colombia que busca construir una comunidad donde empresarios y emprendedores innovadores tienen la oportunidad de superar las barreras más difíciles. A través de un proceso que incluye cuatro retos los empresarios que hagan parte de ALDEA podrán conectarse con mentores, asesores, inversionistas y entidades de crédito, entre otros actores clave, teniendo como punto de encuentro una plataforma virtual.</p>
                    <h6 class="about-subtitle">Etapas del programa</h6>
                    <p class="white-text">Queremos que tus ideas crezcan, por esta razón construimos un programa para que postules tu emprendimiento y puedas ser evaluado por expertos emprendedores, brindándote muchos beneficios</p>
