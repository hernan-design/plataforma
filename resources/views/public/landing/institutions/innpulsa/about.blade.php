			                    <h6 class="reto-title">Tercer reto: <b>¡Conéctate con asesores!</b></h6>
			                    <p class="reto-text">De acuerdo con el concepto emitido en la Conversación con Expertos, iNNpulsa Colombia asignará una llave de acceso al empresario o emprendedor, con la cual podrá acceder a servicios especializados prestados por asesores (personas naturales y jurídicas), habilitados previamente por iNNpulsa Colombia.</p>
								<p class="reto-text">Los servicios especializados a los que tendrán acceso los empresarios y emprendedores se enmarcan entre otras temáticas:</p>
								<ul class="reto-list">
