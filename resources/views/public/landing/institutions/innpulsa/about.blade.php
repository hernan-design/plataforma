			                    <h6 class="reto-title">Cuarto reto: <b>¡Levantemos capital!</b></h6>

			                    <p class="reto-text">Además de servicios especializados, el empresario o emprendedor que haga parte de ALDEA y requiera recursos para apalancar su crecimiento, tendrá la oportunidad de recibir apoyo dirigido a identificar sus necesidades de financiación y, a través de un análisis, iNNpulsa Colombia o quien ésta determine, identificará y recomendará la(s) posibles fuentes (s) de recursos más apropiada(s), de acuerdo con su estructura financiera y estrategia de crecimiento; estas podrán ser productos y/o servicios de crédito, capital a través de diferentes vehículos de inversión, recursos no reembolsables o una configuración entre las fuentes de financiación.</p>

								<p class="reto-text">Condiciones de participación del Cuarto Reto:</p>
								<p class="reto-text">Cada una de las fuentes de financiación disponibles definirá sus condiciones específicas de participación, las cuales serán publicadas mediante invitaciones o convocatorias independientes. Para el caso de crédito e inversión, las condiciones serán definidas directamente por las mismas e iNNpulsa Colombia actuará como un facilitador de la conexión, por lo que no asume responsabilidad alguna en el proceso.</p>
