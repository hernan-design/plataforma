			                    <h6 class="reto-title">Segundo reto: <b>¡Conversa con expertos!</b></h6>
			                    <p class="reto-text">Una vez superado el Primer Reto, el empresario o emprendedor tendrá la
								oportunidad de conversar con expertos que lo retarán a actuar en grande. A través de esta conversación con Expertos (uno en financiación de empresas, otro sectorial y un tercero en desarrollo de negocios), se evaluará, asignará una calificación y se definirá el(los) tipo(s) de servicio(s) necesario(s) para el crecimiento de su negocio.</p>
								<p class="reto-text">Como resultado, iNNpulsa Colombia entregará, una llave de acceso al empresario o emprendedor que obtenga el puntaje mínimo requerido. Esta podrá ser de tres tipos:</p>
								<ul class="reto-list">
									<li><p class="reto-text">Tipo 1 por un valor de hasta veinte millones de pesos ($20.000.000),</p></li>
									<li><p class="reto-text">Tipo 2 por un valor de hasta cuarenta millones de pesos ($40.000.000), o</p></li>
									<li><p class="reto-text">Tipo 3 por un valor de hasta sesenta millones de pesos ($60.000.000)</p></li>
								</ul>
								<br>
								<p class="reto-text">Con esta Llave de Acceso, el empresario o emprendedor podrá acceder a uno o varios servicios especializados ofrecidos por asesores previamente contratados por INNPULSA COLOMBIA.</p>
