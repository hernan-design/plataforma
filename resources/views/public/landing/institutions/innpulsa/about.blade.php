									<li><p class="reto-text">Aceleración de negocios.</p></li>
									<li><p class="reto-text">Asesorías tributarias, financieras, legales y/o jurídicas.</p></li>
									<li><p class="reto-text">Asesorías en propiedad intelectual.</p></li>
									<li><p class="reto-text">Espacios de coworking.</p></li>
								</ul>
								<br>
								<p class="reto-text">El empresario o emprendedor deberá seleccionar del listado de Asesores de Servicios Especializados, habilitados por iNNpulsa Colombia, el que considere más adecuado para resolver las necesidades críticas y detonar el crecimiento de su negocio, con base en las recomendaciones dadas el grupo de expertos.</p>
								<p class="reto-text">Una vez el empresario o emprendedor seleccione su Asesor de Servicios Especializados deberá firmar el acuerdo de negociación*, trámite que deberá realizar en los 20 días hábiles posteriores a la fecha de notificación enviada por iNNpulsa Colombia.</p>
